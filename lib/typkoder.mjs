// Typ från Skatteverkets fil -> klartext. En tresiffrig kod översätts (gammal text om taxeringsåret
// är känt och tidigt nog); text och okända koder lämnas som de är.
export function typText(typ, ar) {
  const s = String(typ ?? '').trim();
  const kod = /^\d{3}$/.test(s) ? Number(s) : null;
  if (kod == null) return s || null;
  for (const [tom, koder] of GAMLA) if (ar && ar <= tom && koder[kod]) return koder[kod];
  return AKTUELLA[kod] ?? s;
}
